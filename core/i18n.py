def translate_tree(root):
    """Один проход по готовому окну: тексты, заданные в конструкторах виджетов."""
    if _lang == "ru":
        return
    from PySide6 import QtWidgets as W
    widgets = [root] + root.findChildren(W.QWidget)
    for w in widgets:
        if isinstance(w, (W.QLabel, W.QAbstractButton)):
            t = w.text()
            n = tr(t)
            if n != t:
                w.setText(n)
        if isinstance(w, (W.QLineEdit, W.QTextEdit)):
            t = w.placeholderText()
            if tr(t) != t:
                w.setPlaceholderText(tr(t))
        if w.toolTip() and tr(w.toolTip()) != w.toolTip():
            w.setToolTip(tr(w.toolTip()))
        if isinstance(w, W.QComboBox):
            for i in range(w.count()):
                w.setItemText(i, tr(w.itemText(i)))
        if isinstance(w, W.QTableWidget):
            for i in range(w.columnCount()):
                it = w.horizontalHeaderItem(i)
                if it:
                    it.setText(tr(it.text()))

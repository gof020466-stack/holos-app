def default_language() -> str:
    """Первый запуск: язык Windows (украинский, русский), иначе английский."""
    try:
        from PySide6.QtCore import QLocale
        name = QLocale.system().name()[:2]
    except Exception:
        name = "ru"
    return name if name in LANGS else "en"


def installer_language(app_dir: str) -> Optional[str]:
    """[v3.2.2, 20.11.2026] Первый запуск: язык, выбранный в окне установщика (Inno Setup пишет его в реестр).
    Только если установщик ставил именно эту папку — иначе None."""
    try:
        import os
        import winreg
        base = r"Software\Microsoft\Windows\CurrentVersion\Uninstall"
        here = os.path.normcase(os.path.abspath(app_dir))
        for app_id in ("Holos-BuckNeverBarks_is1", "Holos-Test_is1"):
            try:
                with winreg.OpenKey(winreg.HKEY_CURRENT_USER, base + "\\" + app_id) as key:
                    path = winreg.QueryValueEx(key, "Inno Setup: App Path")[0]
                    lang = winreg.QueryValueEx(key, "Inno Setup: Language")[0]
            except OSError:
                continue
            root = os.path.normcase(os.path.abspath(path))
            if (here == root or here.startswith(root + os.sep)) and lang in LANGS:
                return lang
    except Exception:
        pass
    return None


